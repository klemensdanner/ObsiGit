public enum GraphKind {
    GRAPH_AM,           // undirected graph implemented with an adjacency matrix
    GRAPH_AL,           // undirected graph implemented with an adjacency list
    DIGRAPH_AM,         // directed graph implemented with an adjacency matrix
    DIGRAPH_AL,         // directed graph implemented with an adjacency list
    WEIGHTED_DIGRAPH_AM // directed graph with weighted edges implemented with an adjacency matrix
}
